package gomain

import "testing"

func TestToV03(t *testing.T) {
	const oldMain = "func main() {\n\tif err := _fc_main(fincrt.DefaultStdio()); err != nil {\n\t\t_, _ = os.Stderr.WriteString(\"error: \" + err.Error() + \"\\n\")\n\t\tos.Exit(1)\n\t}\n}\n"
	const newMain = "func main() {\n\tfincrt.MainExit(_fc_main(fincrt.DefaultStdio()))\n}\n"
	const head = "// Code generated by finc0 from FinCore sources. DO NOT EDIT.\n\npackage main\n\n"
	want := head + "import (\n\t\"fincore/runtime/fincrt\"\n)\n\nfunc _fc_main(io fincrt.Stdio) error { return nil }\n\n" + newMain
	for _, imports := range []string{"import (\n\t\"fincore/runtime/fincrt\"\n\t\"os\"\n)\n", "import (\n\t\"os\"\n)\n"} {
		old := head + imports + "\nfunc _fc_main(io fincrt.Stdio) error { return nil }\n\n" + oldMain
		if got := string(ToV03([]byte(old))); got != want {
			t.Errorf("got\n%s\nwant\n%s", got, want)
		}
	}
	if got := string(ToV03([]byte(want))); got != want {
		t.Errorf("v0.3 source changed:\n%s", got)
	}
	noMain := head + "import (\n\t\"os\"\n)\n"
	if got := string(ToV03([]byte(noMain))); got != noMain {
		t.Errorf("source without main changed:\n%s", got)
	}
}
