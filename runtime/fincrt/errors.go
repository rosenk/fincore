package fincrt

import (
	"errors"
	"os"
)

// Sentinel errors of the FinCore standard library (spec 10.1). They are
// distinct values and must be compared with ==.
var (
	ErrEOF       = errors.New("fincore: EOF")
	ErrTimeout   = errors.New("fincore: timeout")
	ErrCancelled = errors.New("fincore: cancelled")
	ErrZeroWrite = errors.New("fincore: zero-byte write")
	ErrClosed    = errors.New("fincore: use of closed resource")
	ErrIO        = errors.New("fincore: I/O error")
	ErrNotFound  = errors.New("fincore: not found")
	ErrMaxDepth  = errors.New("fincore: maximum depth reached")
	ErrArenaFull = errors.New("fincore: arena full")
	ErrExec      = errors.New("fincore: exec failed")
	// ErrParse is an extension to the spec: returned by ParseUint on
	// malformed or overflowing input.
	ErrParse = errors.New("fincore: invalid number")
	// ErrReported (v0.3, docs/semantics_decisions.md 156): the failure has
	// already been reported; a driver main returning it exits with status
	// 1 without printing (MainExit).
	ErrReported = errors.New("fincore: failure already reported")
)

// MainExit ends the program with the result err of the FinCore driver main
// (v0.3, decision 156). The Go main generated by finc since v0.3 is
//
//	func main() {
//		fincrt.MainExit(_fc_main(caps...))
//	}
//
// nil: MainExit returns, main returns and the process exits with status 0.
// ErrReported: exit with status 1 without output. Any other error: print
// `error: <err>` to stderr and exit with status 1 (spec 9.6).
//
// Go generated by older finc versions (the seed v0.2.0) prints and exits
// inline and does not call MainExit; it gets the v0.2 behaviour.
func MainExit(err error) {
	if err == nil {
		return
	}
	if err != ErrReported {
		_, _ = os.Stderr.WriteString("error: " + err.Error() + "\n")
	}
	os.Exit(1)
}
