package fincrt

import (
	"os"
	"runtime"
	"strings"
	"sync/atomic"
)

// Sentinel errors of the FinCore standard library (spec 10.1). They are
// distinct values and must be compared with ==.
var (
	ErrEOF       error = &sentinel{"fincore: EOF"}
	ErrTimeout   error = &sentinel{"fincore: timeout"}
	ErrCancelled error = &sentinel{"fincore: cancelled"}
	ErrZeroWrite error = &sentinel{"fincore: zero-byte write"}
	ErrClosed    error = &sentinel{"fincore: use of closed resource"}
	ErrIO        error = &sentinel{"fincore: I/O error"}
	ErrNotFound  error = &sentinel{"fincore: not found"}
	ErrMaxDepth  error = &sentinel{"fincore: maximum depth reached"}
	ErrArenaFull error = &sentinel{"fincore: arena full"}
	ErrExec      error = &sentinel{"fincore: exec failed"}
	// ErrParse is an extension to the spec: returned by ParseUint on
	// malformed or overflowing input.
	ErrParse error = &sentinel{"fincore: invalid number"}
)

// sentinel is the type of the sentinel errors.
type sentinel struct{ msg string }

// stderrUsed records that the program has written to stderr through
// Stdio.WriteStderr.
var stderrUsed atomic.Bool

// Error returns the message of the sentinel.
//
// Failure report of a driver main (v0.3, docs/semantics_decisions.md 156):
// when main returns a non-nil error, the process prints `error: <err>` to
// stderr and exits with status 1, unless the program has already written
// to stderr (Stdio.WriteStderr). Then it has reported the failure itself,
// and the process only exits with status 1.
//
// The Go main generated by every finc version, including the seed v0.2.0
// whose stage 1 the bootstrap links against this runtime, is
//
//	if err := _fc_main(...); err != nil {
//		_, _ = os.Stderr.WriteString("error: " + err.Error() + "\n")
//		os.Exit(1)
//	}
//
// and FinCore code cannot call Error() (an error has no text in the
// language). So a call of Error() from main.main is that report, and it
// exits with status 1 right there when the line must be left out. Other
// callers (Go tests, the runtime) always get the message.
func (e *sentinel) Error() string {
	if stderrUsed.Load() && calledFromMain() {
		os.Exit(1)
	}
	return e.msg
}

// calledFromMain reports whether the caller of Error is the generated Go
// main (main.main).
func calledFromMain() bool {
	var pcs [8]uintptr
	n := runtime.Callers(1, pcs[:])
	frames := runtime.CallersFrames(pcs[:n])
	for {
		f, more := frames.Next()
		if !strings.HasPrefix(f.Function, "fincore/runtime/fincrt.") && f.Function != "runtime.Callers" {
			return f.Function == "main.main"
		}
		if !more {
			return false
		}
	}
}
